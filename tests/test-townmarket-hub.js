function mkTowns(n, extra) {
  const t = {};
  for (let i = 1; i <= n; i += 1) {
    t["Town" + String(i).padStart(3, "0")] = {
      active: 10 + i, median_list: 400000 + i * 1000, median_price_per_sqft: i % 7 === 0 ? null : 200 + i, ...(extra || {}),
    };
  }
  return t;
}
