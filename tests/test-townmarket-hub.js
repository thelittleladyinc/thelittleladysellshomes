function tmpDir() { return fs.mkdtempSync(path.join(os.tmpdir(), "townstats-")); }

// One in-process hub run against a temp copy of the committed file.
async function run({ env = GOOD_ENV, responses = [reply(200, mkPayload())], current = mkCurrent(), now = NOW, dir = null } = {}) {
  const d = dir || tmpDir();
  const file = path.join(d, "town_market.json");
  if (current !== null) fs.writeFileSync(file, typeof current === "string" ? current : JSON.stringify(current, null, 2) + "\n");
  const before = fs.existsSync(file) ? fs.readFileSync(file) : null;
  const out = [];
  const err = [];
  const calls = [];
  const sleeps = [];
  const fetchImpl = async (url, init) => {
    calls.push({ url, init });
    const r = responses[Math.min(calls.length - 1, responses.length - 1)];
    if (r.throws) throw r.throws;
    return r.res;
  };
  const result = await tool.runHub({
    env, fetchImpl, now, outPath: file, sleep: async (ms) => { sleeps.push(ms); },
    log: (m) => out.push(m), errLog: (m) => err.push(m),
  });
  const after = fs.existsSync(file) ? fs.readFileSync(file) : null;
  EVERYTHING.push(out.join("\n"), err.join("\n"));
  return {
    result, calls, sleeps, out, err, file, dir: d, before, after,
    said: out.concat(err).join("\n"),
    untouched: before !== null && after !== null && Buffer.compare(before, after) === 0,
    clean: fs.readdirSync(d).join(",") === "town_market.json",
  };
}

// A run that must be refused, leaving the committed file exactly as it was.
async function refused(label, opts, reason, extra) {
  const r = await run(opts);
  check(`${label}: refused`, r.result.ok === false, JSON.stringify(r.result));
  check(`${label}: says why (${reason})`, reason.test(r.result.reason || ""), r.result.reason);
  check(`${label}: committed file byte-identical, no temp file left`, r.untouched && r.clean);
  check(`${label}: nothing printed carries the key or the address`, !leaks(r.said));
  if (extra) extra(r);
  return r;
}

