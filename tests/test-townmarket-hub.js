// answers GET /v1/market/towns with the SAME JSON as build/data/town_market.json
// (header x-hub-key, base address HUB_API_URL). The hub is built separately, so
// every check here runs against a fake of that contract: an injected fetch, and a
// loopback server on 127.0.0.1. Nothing here calls a live API.
//
// What this pins:
//   - unless TOWN_STATS_SOURCE=hub (or --source hub), nothing changes: the default
//     and "github" paths read the Signature file and never contact the hub;
//   - a good answer is written; EVERY way it can go wrong exits non-zero and leaves
//     the committed file byte-identical (and no temp file behind);
//   - the key is never printed, and neither is the address;
//   - the workflow and the Netlify build only reach the hub when the setting says so.
